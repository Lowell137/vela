#!/usr/bin/env python3
"""Theme icon names used by Vela's QML/C++ sources -> docs/icons.md.

Usage: scripts/icon-inventory.py [--write]   (needs a breeze theme installed)
A literal counts as an icon name when it is kebab-case and either sits on a
line mentioning icon/Icon/image://icon, or exists in the breeze theme.
"""
import re, sys, collections
from pathlib import Path

root = Path(__file__).resolve().parents[1]
comps = ["shell", "settings", "explorer", "calculator", "notepad", "paint", "photos",
         "mediaplayer", "taskmanager", "terminal", "capture", "lock", "polkit", "common"]
lit = re.compile(r'"([a-z][a-z0-9]*(?:-[a-z0-9]+)+|[a-z][a-z0-9]+\.[a-z0-9.]+)"')
ignore = {"icon-name", "icon-static", "image-data", "app-icon"}  # property names, not icons
ctx = re.compile(r'[iI]con|image://icon')
breeze = set()
for base in ["/usr/share/icons/breeze"]:
    for p in Path(base).rglob("*.svg"):
        breeze.add(p.stem)
fluent = {p.stem for p in (root / "common/fluent").glob("*.svg")}
names = collections.defaultdict(lambda: collections.Counter())
for c in comps:
    for p in (root / c).rglob("*"):
        if p.suffix not in (".qml", ".cpp", ".h") or "build" in p.parts or "tests" in p.parts:
            continue
        for line in p.read_text(errors="ignore").splitlines():
            if line.lstrip().startswith(("//", "import", "#include")):
                continue
            for m in lit.finditer(line):
                n = m.group(1)
                if n in ignore:
                    continue
                if n in breeze or n in fluent or (ctx.search(line) and "-" in n and n.islower()):
                    names[n][c] += 1

def category(n):
    for key, cat in [("audio", "Audio"), ("media", "Media"), ("network", "Network"), ("bluetooth", "Network"),
                     ("window", "Window"), ("go-", "Navigation"), ("folder", "Files"), ("document", "Files"),
                     ("text-", "Files"), ("image", "Files"), ("edit", "Edit"), ("view", "View"),
                     ("preferences", "Settings"), ("battery", "Power"), ("system", "Power"),
                     ("dialog", "Status"), ("notification", "Status"), ("weather", "Weather"),
                     ("applications", "Apps"), ("utilities", "Apps"), ("user", "Places")]:
        if n.startswith(key):
            return cat
    return "Other"

rows = []
for n, cnt in names.items():
    rows.append((n, sum(cnt.values()), sorted(cnt), n in breeze, n in fluent))
rows.sort(key=lambda r: (-r[1], r[0]))
missing = [r for r in rows if not r[3]]
out = ["# Icon inventory", "",
       "Generated by `scripts/icon-inventory.py --write`: theme icon names found as string",
       "literals in the sources, checked against the Breeze theme and `common/fluent`",
       "(Vela's own drawings, used first). Dynamic names (built at run time, app icons",
       "from .desktop files) are not listed.", "",
       "%d unique names; %d are not in Breeze (%d of those have a `common/fluent` drawing)."
       % (len(rows), len(missing), sum(1 for r in missing if r[4])), ""]
def table(rs):
    t = ["| Name | Uses | Components | Breeze | Own (fluent) |", "| --- | ---: | --- | :-: | :-: |"]
    for n, k, cs, b, f in rs:
        t.append("| `%s` | %d | %s | %s | %s |" % (n, k, ", ".join(cs), "yes" if b else "**no**", "yes" if f else ""))
    return t
out += ["## The vela theme and licenses", "",
        "`icons/vela` (installed as `vela` and `vela-dark`) holds the critical icons (WiFi",
        "levels, Bluetooth, volume, brightness, settings, search, folder, file, power,",
        "bell, battery) as Microsoft's Fluent System Icons, and Vela's own window buttons",
        "(options in `docs/icon-options/`). It inherits `Fluent`, `breeze`, `hicolor`.",
        "Style sheet: `docs/icons-style-sheet.html`. Licenses:", "",
        "- Fluent System Icons (Microsoft, MIT): `icons/fluent-source`, `common/fluent` and",
        "  the theme's copies; text in `icons/vela/LICENSE-fluentui-system-icons`.",
        "  Only the SVGs in use are included.",
        "- vinceliuice/Fluent-icon-theme (GPL-3.0): not copied; an optional separate package",
        "  that `vela` inherits when installed (AUR `fluent-icon-theme-git`).",
        "- No Windows icons or Segoe fonts are used.", "",
        "## Not in Breeze (fall back to the generic icon unless we draw them)", ""] + table(missing) + [""]
bycat = collections.defaultdict(list)
for r in rows:
    if r[3]:
        bycat[category(r[0])].append(r)
for cat in sorted(bycat):
    out += ["## " + cat, ""] + table(bycat[cat]) + [""]
text = "\n".join(out)
if "--write" in sys.argv:
    (root / "docs/icons.md").write_text(text)
else:
    print(text)
